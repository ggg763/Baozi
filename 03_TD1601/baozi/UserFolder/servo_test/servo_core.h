/******************************************************************************
 * @file     servo_core.h
 * @brief    舵机控制层（基于 servo_pins.h 的通路配置）—— 供动作/情绪代码调用
 *
 * 比"直接操作 csi_pwm"省事一层：
 *   servo_core_init()              引脚复用 + PWM 控制器初始化 + compare 校准 + 两路回中位 + 打开输出
 *   servo_set_pulse(ch, pulse_us)  软限位钳制 + **只写 compare**（脉宽）
 *
 * ★ 2026-09：输出方式由"每步 stop→config→start"改成【只写 compare】——
 *   前者每步都会关一下输出使能，两路关的时刻不同 → 8 字这类两轴同时运动的动作
 *   会看起来"两轴不同步/有时延"。详见 servo_core.c 头部说明。
 *
 * 通道直接用 servo_pins.h 的 SERVO_YAW_CH / SERVO_PITCH_CH（当前 YAW=PA29/csi_ch 3、
 * PITCH=PA27/csi_ch 2）。中位/限位是实测值，换舵机后需重新标定 —— 可烧
 * servo_range_test 用串口命令 `w<us>` 逐步试出中位与极限；
 * 或烧 servo_motion_test（TEST_ENTRY=5）串口直接播动作库，看有没有超限告警。
 * 【最近一次标定：2026-09；2026-10-31 试过收窄，动作库跑不通，已回退】
 ******************************************************************************/
#ifndef _SERVO_CORE_H_
#define _SERVO_CORE_H_

#include <stdint.h>
#include "servo_pins.h"

/* 中位脉宽（us）—— 【2026-09 上板实测】
 *
 * ★ 2026-10-31 来回过一次，记在这里免得再踩：
 *   当天用手动 `w` 逐点试，把中位改成 960、上限收到 1440（PITCH 1320），
 *   理由是"960 时机构才正、1440 就顶住"。结果动作库跑不动了 ——
 *   强情绪下幅度是 ×1.2(基准) ×1.38(增益)，YAW 算到 1457、PITCH 1398，
 *   全部越过新限位 → 全程顶死 → 卡顿 + 堵转。
 *   换回下面这组值后动作库能正常跑完（动作实际落点最大 YAW 1497 / PITCH 1398，
 *   距 1700/1600 还有 200us 余量），所以【以动作库能跑为准】。
 *
 *   教训：软限位不能只看"手动单点最远能到哪"，要看"动作库真的用得到多远"。
 *   要收限位就得同时把动作幅度按比例收，否则等于让动作顶在墙上跑。
 *
 * ★ 2026-11 再次按要求把【正向】上限收到 YAW 1440（中位+440us=40°）/
 *   PITCH 1320（中位+220us=20°）。这次与 10-31 那次的区别：
 *     · 中位不动（仍 1000/1100，10-31 那次连中位一起改到 960）；
 *     · MIN 不动（只收正向上限）；
 *     · 已经按"各情绪实际 amp"重算过动作落点（不是笼统按 1.38 最坏值）——
 *       实机 amp 上限由情绪决定：happy 1125 / surprised 1100 / loving 1050 /
 *       angry 975 / sad 825，待机 neutral 950×(curiosity 0.85~1.15) ≤ 1093。
 *   核对结果（系数 = 1.2 × amp/1000）：
 *     YAW   待机巡视 1393 / 开心 1324 / 八字 1337 / 生气 1310  —— 全部 < 1440 ✓
 *     PITCH 唯一贴顶的是惊讶抬头 SURPRISED_PITCH_UP：180×1.32 → 1337 > 1320，
 *           会被截到 1310（差 17us ≈ 1.5°，肉眼看不出；想彻底消掉就把该宏
 *           从 180 降到 160，落点 1311）。
 *   留 SAFE_MARGIN_US(10us) 的余量后，能用的最高点是 1430 / 1310。*/
#define SERVO_YAW_CENTER     1000U      /* 水平 PA29 实测中位 */
#define SERVO_PITCH_CENTER   1100U      /* 垂直 PA27 实测中位 */

/* 行程限位（us）。
 * MIN 是 2026-09 上板实测的安全下限；MAX 是 2026-11 按要求收窄的【正向】上限
 * （YAW +40° / PITCH +20°，都是从中位算起的绝对脉宽）。
 * ⚠️ 再想收窄前先算一遍动作库的最大落点：偏移 × MOVE_AMP_BASE(1.2) × 该情绪的实际 amp。
 *    用"1.2×1.38 最坏值"会高估（那个 1.38 只出现在待机动作上，而待机动作幅度反而最小）。*/
#define SERVO_YAW_MIN        300U       /* 水平实测下限 */
#define SERVO_YAW_MAX        1440U      /* 水平正向上限：中位+440us = 40°（2026-11）*/
#define SERVO_PITCH_MIN      800U       /* 垂直实测下限 */
#define SERVO_PITCH_MAX      1320U      /* 垂直正向上限：中位+220us = 20°（2026-11）*/

/* 初始化：引脚复用 + PWM 控制器 + 两路回中位。返回 0 成功，-1 失败 */
int servo_core_init(void);

/* 设置某通道脉宽（us，自动限位钳制并做输出闸门修正）。
 * 返回 0 成功；传入不属于本工程的通道号返回 -1。 */
int servo_set_pulse(uint32_t ch, uint32_t pulse);

/* ★ 2026-10：总线仲裁钩子 —— 解决"舵机一动、屏幕就闪白块"
 *
 * 背景：LCD 整屏刷新是 60 段 DMA，DMA 要持续从 SRAM 取数喂 SPI FIFO（走 AHB）；
 *       而本文件改脉宽是写 PWM 寄存器（也走 AHB）。两者撞上 → DMA 取数延迟 →
 *       SPI FIFO 被抽空 → 那一段像素时序断 → 屏幕上出现错位白块。
 *       实测：把 PWM 写入短路掉（DRY_RUN）就完全不闪；舵机一动，尤其是眨眼
 *       这种高频重绘时就闪 —— 与"总线争用"的推断完全吻合。
 *
 * 解法：让 PWM 写入避开 DMA 窗口。渲染端在"开始/结束传输"以及"每段之间的空隙"
 *       调用本函数；busy=1 时写入只登记不落地，busy=0 时立刻补写。
 *       一帧有 60 个段间空隙，所以舵机最多滞后一个段（≈1ms），完全无感。
 *
 * 用法（渲染端）：face_set_bus_callback(servo_bus_event);
 */
void servo_bus_event(int busy);

#endif /* _SERVO_CORE_H_ */
