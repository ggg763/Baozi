/******************************************************************************
 * @file     video_tri_test.c
 * @brief    全屏流式渲染：黄色等边三角形绕屏幕中心 360° 原地自转
 *
 * 底座：官方 video.c + "每帧一次全屏 RAMWR 事务、像素 CPU 合成"（已验证
 * 可靠，干净稳定）。本文件把之前失败的旋转三角形用该底座重做：
 *   - 三角形三顶点每帧按角度 theta 旋转（整数定点 sin/cos 表，无 libm）
 *   - 逐像素用"当前帧顶点"的边函数 + 重心符号判断黄/浅蓝
 *   - 无 DMA、无局部窗口、无帧缓冲
 *
 * 帧率估算：整屏 230400 像素轮询发送为主（同全屏纯色填充量级），
 * 每帧约几十~百 ms，theta 每帧 +3° 约为 ~8s/圈。
 *
 * 入口：video_tri_test() —— 由 src/main.c 调用
 ******************************************************************************/

