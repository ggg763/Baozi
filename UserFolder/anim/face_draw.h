/******************************************************************************
 * @file     face_draw.h
 * @brief    v9 表情图元光栅器 —— 8 种形状 + 逐行区间 + 抗锯齿
 *
 * 设计要点（与 face_render.c 的分工）：
 *   本文件只回答"这一行这个部件覆盖了哪些像素"，不碰屏幕、不碰 DMA。
 *   face_render.c 负责把覆盖度调色写进行缓冲、分段 DMA 上屏。
 *   这样图元可以在 PC 上单独编译、跑出图与模拟器逐像素对比。
 *
 * 为什么是"逐行区间"而不是逐像素判定：
 *   480×480 = 230k 像素，逐像素判内外的成本随部件数线性上升；
 *   而每个图元在一条扫描线上的解都是闭式的（圆/椭圆/胶囊/月牙），
 *   一行只需求 1~3 个 x 区间，成本与面积无关。
 *
 * 坐标与单位（与模拟器、与 v9 规格完全一致）：
 *   全部几何量用 **1/2 像素**，原点在屏幕中心，y 向下。
 *   rx/ry 是半径（不是直径）。屏幕 480×480 → 半像素坐标范围 ±480。
 *   内部计算用 **1/256 像素** 定点，端点的小数部分就是覆盖率。
 *
 * 抗锯齿：
 *   横向 —— 区间端点带小数，按覆盖率上灰（1/256 精度）。
 *   纵向 —— 每行取 2 条子扫描线（y±0.25），各计 1/2 权重。
 *   两者相乘得到 3 级以上的边缘灰阶，圆的上下顶点不再是台阶。
 ******************************************************************************/

#ifndef _FACE_DRAW_H_
#define _FACE_DRAW_H_

#include <stdint.h>

#define FD_W        480
#define FD_H        480
#define FD_CX       240
#define FD_CY       240

/* 一帧最多几个部件。v9 里最多的 idea 有 7 个，留 12 有余量。
 * 定义在这里而不是 face_render.h：模型层（face_model.c）也要用它分配暂存数组，
 * 而模型层不该依赖"屏幕"这个头文件。 */
#define FD_MAX_PARTS 12

/* ---------------------------------------------------------------- 图元种类 */
enum {
    FD_SUP = 0,     /* 超椭圆：n=2 是椭圆，n>2 越接近圆角方 */
    FD_CUT,         /* 椭圆 ∩ 半平面（怒眼 / D 形嘴 / 平顶半月） */
    FD_CRES,        /* 外椭圆 − 同尺寸纵向偏移的内椭圆（月牙 / 锥形弧） */
    FD_CAP,         /* 胶囊：线段 + 圆头（腮红斜纹 / 泪 / 汗 / 嘴线） */
    FD_DISC,        /* 正圆 */
    FD_RING,        /* 圆环（睡眠气泡 / 圈圈） */
    FD_HEART,       /* 心形：左右两圆 + 下方三角 */
    FD_STAR         /* 星形：外顶点与内顶点交替（多边形，奇偶填充） */
};

/* ---------------------------------------------------------------- 角色 */
/* 只有"眼睛"会被眨眼/视线/尺寸缩放作用；嘴吃张嘴量；其余不吃。 */
enum {
    FR_EYE = 0,
    FR_MOUTH,
    FR_DECO,
    FR_BLUSH,
    FR_BUBBLE
};

/* ---------------------------------------------------------------- 部件 */
/* 字段复用说明（不用的字段写 0）：
 *   FD_SUP    : x,y 中心  rx,ry 半径  n10 指数×10（0 视作 20）  rot 旋转角
 *   FD_CUT    : x,y 中心  rx,ry 半径  a 法线角(度)  b 偏移（1/2px）
 *   FD_CRES   : x,y 中心  rx,ry 半径  a 纵向偏移 d（1/2px，>0 上拱）
 *   FD_CAP    : x,y 起点  a,b 终点   rx 半径
 *   FD_DISC   : x,y 中心  rx 半径
 *   FD_RING   : x,y 中心  rx 外半径  c 环宽
 *   FD_HEART  : x,y 中心  rx,ry 全宽/全高
 *   FD_STAR   : x,y 中心  rx,ry 半径  c 内径百分比(0..100)
 *
 * alpha 为什么必须有：
 *   切表情时会有"新部件"出现（neutral 没有嘴，laugh 有）。早先用"把半径缩到 0"
 *   做淡入，结果胶囊的端点坐标也被按比例缩向原点 —— 屏幕中央会窜出一条斜线。
 *   改成按不透明度淡入淡出，几何保持原样，这才是正确的做法。
 */
typedef struct {
    uint8_t  kind;      /* FD_* */
    uint8_t  role;      /* FR_* */
    uint8_t  mirror;    /* 1 = 以屏幕中线镜像再画一份（只写左眼即可得到右眼） */
    uint8_t  n10;       /* 超椭圆指数 ×10 */
    uint8_t  alpha;     /* 部件不透明度 0..255（过渡淡入淡出、腮红浓度都用它） */
    int16_t  x, y;      /* 1/2 px */
    uint16_t rx, ry;    /* 1/2 px */
    int16_t  rot;       /* 度 */
    int16_t  a, b;      /* 见上表 */
    int16_t  c;
} fd_part_t;            /* 18 字节 */

/* ---------------------------------------------------------------- 姿势 */
/* 一个姿势 = 一组部件 + 一个前景色。
 * 颜色跟着姿势走是 v9 的决定（loving 粉、angry 红、sad 蓝）：屏是 RGB565，
 * 换色不花任何带宽，却能让同一副形状读出完全不同的情绪。 */
typedef struct {
    const char      *name;
    uint16_t         col;       /* RGB565 前景色 */
    const fd_part_t *parts;
    uint8_t          n;
} fd_pose_t;

/* ---------------------------------------------------------------- 覆盖度 */
/* 单行覆盖缓冲：cov[0..FD_W-1]，0 = 无覆盖，255 = 全覆盖。
 * 用 uint8 而不是 float：ARM/RISC-V 上整数加减比浮点快一个数量级。 */

void fd_cov_clear(uint8_t *cov);

/* 把一个部件在第 y 行（0..FD_H-1）的覆盖累加进 cov。
 *   flip = 0 正常；1 画 x 镜像（后半段右眼就是这么来的）
 *   alpha = 0..255，部件整体不透明度（腮红/气泡用） */
void fd_cov_part(uint8_t *cov, const fd_part_t *p, int y, int flip, uint8_t alpha);

/* ---------------------------------------------------------------- 调色 */
/* 把覆盖度调成 RGB565 写进 line：out[i] = mix(bg, fg, cov[i]*alpha/255) */
void fd_blend_row(uint16_t *line, const uint8_t *cov, uint16_t fg, uint16_t bg);

/* ---------------------------------------------------------------- 自检 */
/* 返回 0 = 正常；非 0 = 某个不变量被破坏（供上板自检用） */
int fd_selftest(void);

#endif /* _FACE_DRAW_H_ */
