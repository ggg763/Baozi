static inline int cos12(int deg) { return g_sin12[((deg + 90) % 360 + 360) % 360]; }
static inline int sin12(int deg) { return g_sin12[((deg % 360) + 360) % 360]; }

/* 以中心 (cx,cy) 旋转半径 r、角度 ang 的点坐标 */
static void polar_xy(int cx, int cy, int r, int ang, int *px, int *py)
{
    *px = cx + ((r * cos12(ang) + 2048) >> 12);
    *py = cy + ((r * sin12(ang) + 2048) >> 12);
}

/* ==================== 测试入口（持续旋转，不黑屏） ==================== */
void qspi_triangle_test(void)
{
    int theta = 0;

    qspi_lcd_init();

    /* 整屏背景只画一次 */
    qspi_fill_rect(0, 0, QSPI_LCD_W, QSPI_LCD_H, COL_BG);

    printf("[tri] yellow equilateral triangle 360 rotate start\r\n");

    for (;;) {
        int x0, y0, x1, y1, x2, y2;

        /* 清上一帧区域（覆盖圆） */
        qspi_fill_circle(CX, CY, R_COVER, COL_BG, COL_BG);

        /* 三个顶点：相隔 120° */
        polar_xy(CX, CY, R_TRI, theta,         &x0, &y0);
        polar_xy(CX, CY, R_TRI, theta + 120,   &x1, &y1);
        polar_xy(CX, CY, R_TRI, theta + 240,   &x2, &y2);

        /* 画黄色实心三角形 */
        qspi_fill_triangle(x0, y0, x1, y1, x2, y2, COL_YEL, COL_BG);

        theta = (theta + 4) % 360;      /* 4°/帧 原地自转 */
    }
}
