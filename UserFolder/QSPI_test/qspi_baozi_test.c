#define R_COVER     180                 /* 每帧背景覆盖圆半径（盖住历史位置） */

/* 地面阴影（固定画一次，低于包子浮动范围） */
#define SHADOW_CY   448
#define SHADOW_RX   128
#define SHADOW_RY   12

