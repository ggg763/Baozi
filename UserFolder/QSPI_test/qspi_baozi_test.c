#define COL_SHADOW  QSPI_RGB565(152, 170, 202)   /* 地面阴影（静态） */

/* ==================== 布局（480x480） ==================== */
#define CX          240                 /* 包子中心 x（固定） */
#define CY_BASE     248                 /* 包子中心 y 基准 */
