/******************************************************************************
 * @file     qspi_baozi_test.c
 * @brief    高分辨率包子动画：绕屏幕中心自转 + 竖直小幅上下浮动（持续循环）
 *
 * 硬件：TD1601 EVB 扩展板 CON2 QSPI 屏（TR230S 480x480），
 *       驱动见同目录 qspi_lcd.c。
 *
 * 设计要点（192KB SRAM 限制，无帧缓冲）：
 *   - 包子用纯几何参数化绘制：皮身大圆 + 底部月牙阴影 + 12 条放射褶纹
 *     （其中 1 条深褶破坏对称）+ 中心收口 + 2 点高光；
 *   - 褶纹/高光/收口都"贴在包子表面"，整组绕中心随角度 theta 旋转，
 *     因此能清晰看出包子在自转；
 *   - 浮动 = 包子整体 y 做小幅度正弦上下（FLOAT_A px），同时地面阴影
 *     固定不动，强化"上下移动"感；
 *   - sin/cos 用整数定点查表（无 libm 依赖），角度全为整数度；
 *   - 每帧只用固定几个大窗口 + 若干小圆点窗口重绘包子区域，无残留。
 *
 * 入口：qspi_baozi_test() —— 由 src/main.c 调用
 ******************************************************************************/

