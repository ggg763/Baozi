static inline int cos12(int deg)   { return g_sin12[((deg + 90) % 360 + 360) % 360]; }
static inline int sin12(int deg)   { return g_sin12[((deg % 360) + 360) % 360]; }

/* 包子表面一点（与包子相对极坐标 r/ang_deg），按旋转角 theta 与中心 cy 定位 */
static void spot(int cx, int cy, int r, int ang, int rr, uint16_t color)
{
    int x = cx + ((r * cos12(ang) + 2048) >> 12);
    int y = cy + ((r * sin12(ang) + 2048) >> 12);
    qspi_fill_circle(x, y, rr, color, COL_DOUGH);
}

/* ==================== 单帧绘制 ==================== */
static void draw_baozi(int cy, int theta)
{
    int i, k;

    /* 0. 固定圆心背景覆盖圆（out=BG 无痕，清掉上一帧包子所有位置） */
    qspi_fill_circle(CX, CY_BASE, R_COVER, COL_BG, COL_BG);

    /* 1. 底部月牙：先画整体下移 8px 的深色圆，再画主体圆盖住，留出下缘阴影 */
    qspi_fill_circle(CX, cy + 8, R_DOUGH, COL_EDGE, COL_BG);
    qspi_fill_circle(CX, cy,     R_DOUGH, COL_DOUGH, COL_BG);

    /* 2. 放射褶纹：12 条沿表面转动的弧线，0 号深褶更长更粗（破对称） */
    for (k = 0; k < 12; k++) {
        int deep = (k == 0);
        int r0 = deep ? 34 : 58;            /* 内端半径 */
        int r1 = deep ? 142 : 124;          /* 外端半径 */
        int pr = deep ? 4 : 3;              /* 点半径 */
        uint16_t col = deep ? COL_DEEP : COL_FOLD;
        int a0 = theta + k * 30 - 8;        /* 内端角（弧度弯曲起点） */
        for (i = 0; i <= 9; i++) {
            int r  = r0 + (r1 - r0) * i / 9;
            int a  = a0 + (16 * i) / 9;     /* 内->外角增 16 度，形成旋弯 */
            spot(CX, cy, r, a, pr, col);
        }
    }

    /* 3. 中心收口：小圆 + 内部深点（随包子整体浮动，不随褶转） */
    qspi_fill_circle(CX, cy, 13, COL_COLLAR, COL_DOUGH);
    qspi_fill_circle(CX, cy, 5, COL_DEEP, COL_COLLAR);

    /* 4. 高光：两白点贴在表面随包子转动（out=DOUGH 无痕） */
    spot(CX, cy, 92, theta + 205, 15, COL_HILITE);
    spot(CX, cy, 114, theta + 118, 7, COL_HILITE);
}

/* ==================== 测试入口（持续显示，不黑屏） ==================== */
void qspi_baozi_test(void)
{
    int theta = 0;      /* 自转角度（度） */
    int phase = 0;      /* 浮动相位（度） */

    qspi_lcd_init();

    /* 首帧：整屏背景 + 地面阴影（一次，之后只更新包子区域） */
    qspi_fill_rect(0, 0, QSPI_LCD_W, QSPI_LCD_H, COL_BG);
    qspi_fill_ellipse(CX, SHADOW_CY, SHADOW_RX, SHADOW_RY, COL_SHADOW, COL_BG);

    printf("[baozi] spin + float animation start\r\n");

    for (;;) {
        int dy = (FLOAT_A * g_sin12[phase] + 2048) >> 12;   /* 上下浮动偏移 */
        draw_baozi(CY_BASE + dy, theta);

        theta = (theta + 2) % 360;      /* 自转：2°/帧 */
        phase = (phase + 5) % 360;      /* 浮动相位：5°/帧 */
    }
}
