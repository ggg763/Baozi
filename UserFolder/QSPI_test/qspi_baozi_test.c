/* ==================== 配色（RGB565） ==================== */
#define COL_BG      QSPI_RGB565(186, 222, 248)   /* 背景：淡天蓝 */
#define COL_DOUGH   QSPI_RGB565(255, 240, 211)   /* 包子皮：米白 */
#define COL_EDGE    QSPI_RGB565(203, 168, 128)   /* 底部月牙/皮边：浅棕 */
#define COL_FOLD    QSPI_RGB565(174, 133, 95)    /* 普通褶影：中棕 */
#define COL_DEEP    QSPI_RGB565(133, 92, 60)     /* 深褶/收口深色 */
#define COL_COLLAR  QSPI_RGB565(110, 78, 56)     /* 中心收口 */
